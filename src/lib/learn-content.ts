/**
 * Every entry by its term, plus its Hebrew name, lowercased.
 *
 * The knowledge centre was a destination: a reader had to already know
 * that they did not understand something, leave the page they were on,
 * find the entry and come back. That is the wrong way round. Almost
 * nobody interrupts themselves to go and learn a term — they skim past
 * the number and lose the part of the page that mattered.
 *
 * So the entries are addressable from anywhere a figure is rendered, and
 * `/learn` becomes the index of a thing that lives all over the site
 * rather than the only place it exists.
 */
const INDEX: Map<string, LearnEntry> = (() => {
  const map = new Map<string, LearnEntry>();
  for (const section of LEARN_SECTIONS) {
    for (const entry of section.entries) {
      map.set(entry.term.toLowerCase(), entry);
      if (entry.hebrew) map.set(entry.hebrew.toLowerCase(), entry);
    }
  }
  return map;
})();

/** The entry for a term, by either of its names. Null when the site has
 *  nothing written about it — which is the honest answer, and better than
 *  an affordance that opens onto nothing. */
export function learnEntry(term: string): LearnEntry | null {
  return INDEX.get(term.trim().toLowerCase()) ?? null;
}

/** Which section an entry lives in, for the link back to the centre. */
export function sectionOf(term: string): LearnSection | null {
  const key = term.trim().toLowerCase();
  for (const section of LEARN_SECTIONS) {
    for (const entry of section.entries) {
      if (entry.term.toLowerCase() === key || entry.hebrew?.toLowerCase() === key) {
        return section;
      }
    }
  }
  return null;
}
